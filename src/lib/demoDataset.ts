function makeBands(profile: 'natural' | 'compressed' | 'synthetic'): ExtractedFeatures['frequencyBands'] {
  const labels = [
    '0-300Hz',
    '300-600Hz',
    '600-1kHz',
    '1-2kHz',
    '2-3kHz',
    '3-4kHz',
    '4-6kHz',
    '6-8kHz',
    '8-12kHz',
    '12kHz+',
  ];
  const curves = {
    natural: [72, 100, 88, 74, 58, 44, 32, 22, 14, 8],
    compressed: [60, 86, 100, 92, 81, 68, 52, 18, 7, 3],
    synthetic: [45, 78, 100, 96, 89, 76, 38, 11, 4, 2],
  };
  return labels.map((band, i) => ({ band, energy: curves[profile][i] }));
}

function daysAgo(days: number, hoursOffset: number): Date {
  const d = new Date();
  d.setDate(d.getDate() - days);
  d.setHours(Math.max(0, Math.min(23, d.getHours() - hoursOffset)), 15, 0, 0);
  return d;
}

